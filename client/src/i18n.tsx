export const translations = { en, zh };

export function getLang(): Lang {
  return (localStorage.getItem('studiosage_lang') as Lang) || 'en';
}

export function setLang(lang: Lang) {
  localStorage.setItem('studiosage_lang', lang);
}

export function t(key: string): string {
  const lang = getLang();
  const keys = key.split('.');
  let val: any = translations[lang];
  for (const k of keys) {
    val = val?.[k];
    if (val === undefined) break;
  }
  if (typeof val === 'string') return val;
  // Fallback to English
  val = translations.en;
  for (const k of keys) {
    val = val?.[k];
    if (val === undefined) return key;
  }
  return typeof val === 'string' ? val : key;
}

// For cases where the translation contains {placeholders}
export function tf(key: string, replacements: Record<string, string | number>): string {
  let text = t(key);
  for (const [k, v] of Object.entries(replacements)) {
    text = text.replace(`{${k}}`, String(v));
  }
  return text;
}
